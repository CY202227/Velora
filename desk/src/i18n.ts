export function translate(locale: Locale, key: string, variables: Record<string, string | number> = {}): string {
  const template = messages[locale][key] || messages["zh-CN"][key] || key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`));
}

export function savedLocale(): Locale {
  const value = localStorage.getItem("velora_locale");
  return value === "en" || value === "ja" || value === "zh-CN" ? value : "zh-CN";
}
